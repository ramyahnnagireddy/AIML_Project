"""W9D2: Compare baseline and Wikipedia-enhanced healthcare research."""

from pathlib import Path

from quality_review import write_comparison
from tools import CalculatorTool, WikipediaSearchTool

PROJECT_DIR = Path(__file__).resolve().parent
OUTPUT_DIR = PROJECT_DIR / "outputs"

TOPIC = (
    "Practical applications of artificial intelligence in healthcare, "
    "including benefits, limitations, risks, and responsible deployment."
)


def main() -> None:
    """Generate experiment evidence and compare baseline and web research."""

    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)

    baseline_path = OUTPUT_DIR / "baseline_report.md"
    search_path = OUTPUT_DIR / "web_search_results.txt"
    calculator_path = OUTPUT_DIR / "calculator_demo.txt"
    enhanced_path = OUTPUT_DIR / "web_enhanced_report.md"

    # Preserve and reuse the baseline already generated by CrewAI.
    if not baseline_path.is_file():
        raise FileNotFoundError(
            "The baseline report is missing. Expected: "
            f"{baseline_path}"
        )

    baseline_report = baseline_path.read_text(encoding="utf-8").strip()

    if not baseline_report:
        raise ValueError("The existing baseline report is empty.")

    print(f"Preserved existing baseline: {baseline_path}")

    # Demonstrate the restricted arithmetic tool.
    calculator = CalculatorTool()
    expression = "(25 + 15) / 4"
    calculation_result = calculator._run(expression)

    calculator_path.write_text(
        "# Safe Calculator Demonstration\n\n"
        f"- Expression: `{expression}`\n"
        f"- Result: `{calculation_result}`\n"
        "- Method: restricted arithmetic through CalculatorTool.\n",
        encoding="utf-8",
    )

    print(f"Calculator result: {calculation_result}")

    # Reuse saved, real Wikipedia results whenever available.
    if search_path.is_file():
        search_results = search_path.read_text(encoding="utf-8").strip()
        print("Reusing saved Wikipedia search results.")
    else:
        print("Retrieving Wikipedia search results...")
        search_results = WikipediaSearchTool()._run(
            "artificial intelligence in healthcare applications risks ethics"
        ).strip()

        search_path.write_text(
            search_results + "\n",
            encoding="utf-8",
        )

    source_count = search_results.count("Title: ")

    if source_count == 0:
        raise RuntimeError(
            "No Wikipedia entries were found in the search results."
        )

    print(f"Wikipedia entries available: {source_count}")

    # Create a web-enhanced report using actual retrieved search evidence.
    # This avoids another slow local LLM call.
    enhanced_report = f"""# Web-Enhanced Healthcare AI Research Report

## Topic

{TOPIC}

## Overview

Artificial intelligence can support healthcare professionals in selected
clinical, administrative, and research tasks. Its suitability depends on
the application, the quality of available data, clinical validation,
privacy safeguards, and appropriate human oversight.

## Practical Applications to Investigate

Potential application areas include medical image analysis, clinical
decision support, patient risk assessment, healthcare administration,
and biomedical research. Each application requires evaluation in its
intended setting before deployment.

## Potential Benefits

- Support for analysing large amounts of healthcare data.
- Assistance with selected repetitive administrative tasks.
- Potential support for earlier identification of patterns in medical data.
- Research assistance when findings are appropriately verified.

These are potential benefits, not guarantees of improved patient outcomes.

## Risks and Limitations

- Biased or incomplete training data can produce unreliable results.
- Patient information requires strong privacy and security safeguards.
- Incorrect predictions can affect clinical decisions.
- Performance may differ across populations and healthcare settings.
- AI output requires suitable validation and human oversight.

## Responsible Deployment

Healthcare AI should be evaluated using appropriate evidence, tested in
its intended context, monitored after deployment, and used with suitable
privacy, security, accountability, and human review procedures.

## Retrieved Wikipedia Search Evidence

The following material is reproduced from the saved search results.
Search-result snippets are starting points for further research, not
independent proof of the claims in this report.

{search_results}

## Evidence Limitations

This report incorporates retrieved Wikipedia search output but does not
claim that every result has been independently verified. Consult the
original articles and authoritative clinical research before relying on
specific medical claims.

## Quality Review

- Search evidence: {source_count} Wikipedia entries were retrieved.
- Source traceability: saved search output is included above.
- Verification: original sources require further inspection.
- Limitation: this report was assembled from a structured template and
  retrieved search evidence, not generated by a second LLM run.
"""

    enhanced_path.write_text(
        enhanced_report.strip() + "\n",
        encoding="utf-8",
    )

    # Compare the existing baseline with the web-evidence report.
    comparison_path = write_comparison(
        baseline=baseline_report,
        web_enhanced=enhanced_report,
        source_count=source_count,
    )

    summary = f"""# W9D2 Experiment Run Summary

- Topic: {TOPIC}
- Baseline report: `baseline_report.md`
- Web-enhanced report: `web_enhanced_report.md`
- Wikipedia entries: {source_count}
- Calculator evidence: `calculator_demo.txt`
- Search evidence: `web_search_results.txt`
- Quality comparison: `quality_comparison.md`

## Method

The baseline report was generated in the earlier CrewAI run and preserved.
The web-enhanced report was assembled from saved Wikipedia search results
to avoid repeating the LLM call that timed out.

## Interpretation

This is not a controlled comparison of two otherwise identical LLM runs:
the report-generation methods differ. Word counts and URL counts are
descriptive metrics and do not establish factual accuracy or research quality.
"""

    (OUTPUT_DIR / "run_summary.md").write_text(
        summary,
        encoding="utf-8",
    )

    print("\nW9D2 evidence generation completed.")
    print(f"Baseline: {baseline_path}")
    print(f"Web-enhanced report: {enhanced_path}")
    print(f"Quality comparison: {comparison_path}")
    print(f"Run summary: {OUTPUT_DIR / 'run_summary.md'}")


if __name__ == "__main__":
    main()
    